IBVS_ALT_MIN = _get("IBVS_ALT_MIN", 2.0)  # m     GSD floor (prevents gain blow-up)
IBVS_ALT_MAX = _get("IBVS_ALT_MAX", 30.0)  # m    gain ceiling. Keep ALIGNED with
