# =============================================================================
# IBVS -- visual servoing
# Control law: pixel error -> METRIC ground error (via altitude and focal length) ->
# body-frame velocity. P-only with velocity-slew damping; no derivative term. Commands go
# out as MAV_FRAME_BODY_OFFSET_NED, which eliminates the yaw-induced flyaway class.
# Keep these BELOW the autopilot's WPNAV_SPEED / WPNAV_ACCEL so the approach stays gentle.
# =============================================================================

# Focal length is DERIVED from the camera, so changing resolution or FOV keeps IBVS
# correct without manual edits.
